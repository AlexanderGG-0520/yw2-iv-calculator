import { readFile, writeFile } from "node:fs/promises";

const SOURCE_URL = "https://togenyanweb.appspot.com/Yokai/yw2/yokaiList.html";
const OUTPUT = new URL("../src/engine/yokaiData.generated.ts", import.meta.url);
const allowFallback = process.argv.includes("--allow-fallback");

function decodeHtml(value) {
  return value
    .replace(/<[^>]+>/g, "")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .trim();
}

function parseTable(html) {
  const rows = [];
  for (const rowMatch of html.matchAll(/<tr\b[^>]*>([\s\S]*?)<\/tr>/gi)) {
    const cells = [...rowMatch[1].matchAll(/<td\b[^>]*>([\s\S]*?)<\/td>/gi)]
      .map((match) => decodeHtml(match[1]));
    if (cells.length < 12) continue;

    const number = Number(cells[0]);
    const values = cells.slice(2, 12).map(Number);
    if (!Number.isInteger(number) || values.some((value) => !Number.isFinite(value))) continue;

    const [aHp, aStr, aSpr, aDef, aSpd, bHp, bStr, bSpr, bDef, bSpd] = values;
    if (bHp === 0 && bStr === 0 && bSpr === 0 && bDef === 0 && bSpd === 0) continue;

    rows.push({
      id: "yw2-" + String(number).padStart(3, "0"),
      number,
      name: cells[1],
      baseA: { hp: aHp, strength: aStr, spirit: aSpr, defense: aDef, speed: aSpd },
      baseB: { hp: bHp, strength: bStr, spirit: bSpr, defense: bDef, speed: bSpd },
      source: "togenyan-yw2",
    });
  }
  return rows;
}

async function main() {
  try {
    const response = await fetch(SOURCE_URL);
    if (!response.ok) throw new Error("HTTP " + response.status + " while fetching source table");
    const html = await response.text();
    const rows = parseTable(html);
    if (rows.length < 300) throw new Error("Source parser returned only " + rows.length + " rows");

    const content =
      'import type { YokaiSpecies } from "./types";\n\n' +
      "// Generated by scripts/sync-yokai-data.mjs from " + SOURCE_URL + "\n" +
      "export const GENERATED_YOKAI = " +
      JSON.stringify(rows, null, 2) +
      " as const satisfies readonly YokaiSpecies[];\n";

    await writeFile(OUTPUT, content, "utf8");
    console.log("Generated " + rows.length + " YW2 data rows.");
  } catch (error) {
    if (!allowFallback) throw error;
    await readFile(OUTPUT, "utf8");
    console.warn("Could not refresh YW2 data; using checked-in fallback:", error);
  }
}

await main();
